#!/usr/bin/env node
// Writes windows/NitroNode/NitroNodeAutolinking.g.cpp from nitro.json: the
// HybridObject registration nitrogen generates for Android (NitroNodeOnLoad.cpp)
// and iOS, which it can't generate for Windows. Run by `npm run codegen`, after
// nitrogen.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const { autolinking } = require(path.join(root, 'nitro.json'));

// HybridObjects without an "all" C++ implementation. On Windows NitroNodeOs is
// the C++ HybridOs, as on iOS; NitroNodeDnsInit is Android's (c-ares needs its
// ConnectivityManager), and dns-init.ts doesn't create it elsewhere.
const WINDOWS = {
  NitroNodeOs: 'HybridOs',
  NitroNodeDnsInit: null,
};

const objects = [];
for (const [name, platforms] of Object.entries(autolinking)) {
  let className;
  if (platforms.all !== undefined) {
    if (platforms.all.language !== 'c++') {
      throw new Error(`${name}: only C++ HybridObjects can be autolinked on Windows`);
    }
    className = platforms.all.implementationClassName;
  } else if (name in WINDOWS) {
    className = WINDOWS[name];
  } else {
    throw new Error(`${name} has no Windows implementation: add it to WINDOWS in ${path.relative(root, __filename)}`);
  }
  if (className !== null) {
    objects.push({ name, className });
  }
}

const includes = [...new Set(objects.map(o => o.className))].map(c => `#include "${c}.hpp"`);
const registrations = objects.map(
  ({ name, className }) => `  HybridObjectRegistry::registerHybridObjectConstructor(
    "${name}",
    []() -> std::shared_ptr<HybridObject> {
      static_assert(std::is_default_constructible_v<${className}>,
                    "The HybridObject \\"${className}\\" is not default-constructible! "
                    "Create a public constructor that takes zero arguments to be able to autolink this HybridObject.");
      return std::make_shared<${className}>();
    }
  );`,
);

const source = `///
/// NitroNodeAutolinking.g.cpp
/// Generated by scripts/generate-windows-autolinking.js from nitro.json.
/// DO NOT MODIFY THIS FILE.
///

#include "NitroNodeAutolinking.h"

#include <NitroModules/HybridObjectRegistry.hpp>

${includes.join('\n')}

namespace margelo::nitro::node {

void registerAllHybridObjects() {
  using namespace margelo::nitro;
  using namespace margelo::nitro::node;

${registrations.join('\n')}
}

} // namespace margelo::nitro::node
`;

const out = path.join(root, 'windows', 'NitroNode', 'NitroNodeAutolinking.g.cpp');
fs.writeFileSync(out, source);
console.log(`Wrote ${path.relative(root, out)} (${objects.length} HybridObjects)`);
