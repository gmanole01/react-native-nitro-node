export const ERROR_MAP = new Map<string, number>(Object.entries(ERRORS));
export const ERROR_KEYS = new Set<string>(Object.keys(ERRORS));
export const ERROR_VALUES = new Set<number>(Object.values(ERRORS));

const ERROR_STRING_CACHE = new Map<number, string>();

export function uv_strerror(error: number): string {
  // check for valid error, helps find bugs
  if (!ERROR_VALUES.has(error)) {
    throw new Error(`Unknown UV error: ${error}`);
  }

  if (ERROR_STRING_CACHE.has(error)) {
    return ERROR_STRING_CACHE.get(error) as string;
  }

  // call into native
  const str = NitroUv.uv_strerror(error);

  // cache it
  ERROR_STRING_CACHE.set(error, str);

  return str;
}
